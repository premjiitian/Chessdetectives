/** Same key for the same words, whatever the punctuation. */
export const pinKey = (sentence: string) => sentence.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();

let manifest: Promise<Record<string, string>> | null = null;
/** key -> audio file, generated by scripts/make-pin-voice.py */
export function pinManifest(): Promise<Record<string, string>> {
  manifest ??= fetch(`${import.meta.env.BASE_URL}voice/pin/manifest.json`)
    .then((r) => (r.ok ? r.json() : {}))
    .catch(() => ({}));
  return manifest;
}
export const pinUrl = (file: string) => `${import.meta.env.BASE_URL}voice/pin/${file}`;
